using System.IO;
using System.Windows;
using System.Windows.Automation;
using System.Windows.Controls;
using System.Windows.Data;
using System.Windows.Media;
using Toolbox.Model;

namespace Toolbox.Sidebar;

/// <summary>The New/Edit Credential dialog.</summary>
internal sealed class CredentialEditor : EditorWindow
{
    private readonly AppModel model;
    private readonly CredentialDraft draft;

    public CredentialEditor(AppModel model, CredentialDraft draft)
        : base(draft.IsNew ? "New Credential" : "Edit Credential", 560, 760)
    {
        this.model = model;
        this.draft = draft;
        DataContext = draft;
        AutomationProperties.SetAutomationId(this, "CredentialEditor");

        var form = new FormBuilder();
        form.Section("Credential");
        form.Row("Name", FormBuilder.Text(nameof(CredentialDraft.Name), "Domain admin"));
        form.Row("Username", FormBuilder.Text(nameof(CredentialDraft.Username), @"DOMAIN\user or root"));
        form.Row("Folder", FormBuilder.Text(nameof(CredentialDraft.Folder), "Optional; use / for subfolders"));

        form.Section("Secret");
        var kept = new ComboBox { ItemsSource = CredentialKindChoices.All, HorizontalAlignment = HorizontalAlignment.Stretch };
        kept.SetBinding(System.Windows.Controls.Primitives.Selector.SelectedItemProperty,
                        new Binding(nameof(CredentialDraft.SelectedKind)) { Mode = BindingMode.TwoWay });
        AutomationProperties.SetAutomationId(kept, "Kept");
        form.Row("Kept", kept);

        // Vault
        form.Row("Password", FormBuilder.Secret(value => draft.Password = value, "Password"), nameof(CredentialDraft.IsVault));
        form.Wide(PrivateKeyField(), nameof(CredentialDraft.IsVault));
        form.Row("Key passphrase", FormBuilder.Secret(value => draft.Passphrase = value, "Passphrase"), nameof(CredentialDraft.IsVault));
        form.Note(null, nameof(CredentialDraft.IsVault), textPath: nameof(CredentialDraft.VaultNote));

        // 1Password
        form.Row("Item id", FormBuilder.Text(nameof(CredentialDraft.ItemId), "from op item list"), nameof(CredentialDraft.IsOnePassword));
        form.Row("Account", FormBuilder.Text(nameof(CredentialDraft.Account), "Optional shorthand, e.g. work"), nameof(CredentialDraft.IsOnePassword));
        form.Row("op path", FormBuilder.Text(nameof(CredentialDraft.OpPath), CoreApi.DetectOpPath() ?? "auto-detect"), nameof(CredentialDraft.IsOnePassword));
        form.Note("Fetched with the 1Password CLI when used. Nothing is stored locally.", nameof(CredentialDraft.IsOnePassword));

        // Prompt
        form.Note("Toolbox asks for the password every time this credential is used.", nameof(CredentialDraft.IsPrompt));

        form.Note("Generated by a provider. The next sync replaces your edits.", nameof(CredentialDraft.IsGenerated), warning: true);
        SetForm(form);

        AddButton(draft.IsNew ? "Add" : "Save", Save, isDefault: true, automationId: "EditorSave");
        AddButton("Cancel", Close, isCancel: true, automationId: "EditorCancel");
    }

    public Credential? Saved { get; private set; }

    private FrameworkElement PrivateKeyField()
    {
        var label = new TextBlock { Text = "Private key", VerticalAlignment = VerticalAlignment.Center };
        var load = new Button { Content = "Load Key File…", HorizontalAlignment = HorizontalAlignment.Right };
        load.Click += (_, _) => LoadKeyFile();
        var top = new Grid();
        top.Children.Add(label);
        top.Children.Add(load);

        var box = new TextBox
        {
            AcceptsReturn = true,
            TextWrapping = TextWrapping.NoWrap,
            FontFamily = new FontFamily("Cascadia Mono, Consolas"),
            FontSize = 11,
            Height = 86,
            Margin = new Thickness(0, 6, 0, 0),
            VerticalScrollBarVisibility = ScrollBarVisibility.Auto,
            HorizontalScrollBarVisibility = ScrollBarVisibility.Auto,
        };
        box.SetBinding(TextBox.TextProperty, new Binding(nameof(CredentialDraft.PrivateKey))
        {
            Mode = BindingMode.TwoWay,
            UpdateSourceTrigger = UpdateSourceTrigger.PropertyChanged,
        });
        AutomationProperties.SetAutomationId(box, "PrivateKey");
        AutomationProperties.SetName(box, "Private key");

        var panel = new StackPanel();
        panel.Children.Add(top);
        panel.Children.Add(box);
        return panel;
    }

    private void LoadKeyFile()
    {
        var dialog = new Microsoft.Win32.OpenFileDialog
        {
            Title = "Choose a private key to copy into the vault",
            CheckFileExists = true,
            Filter = "All files (*.*)|*.*",
        };
        var ssh = Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.UserProfile), ".ssh");
        if (Directory.Exists(ssh)) dialog.InitialDirectory = ssh;
        if (dialog.ShowDialog(this) != true) return;
        try
        {
            draft.PrivateKey = File.ReadAllText(dialog.FileName);
            ShowValidation(null);
        }
        catch (Exception e)
        {
            ShowValidation($"Couldn't read {Path.GetFileName(dialog.FileName)}: {e.Message}");
        }
    }

    private async void Save()
    {
        if (draft.ValidationError is { } problem)
        {
            ShowValidation(problem);
            return;
        }
        ShowValidation(null);
        SetBusy(true);
        try
        {
            Saved = await model.SaveCredentialAsync(draft.ToCredential(), draft.ToSecret());
            Accept();
        }
        catch (VaultException e) when (e.IsCancellation)
        {
            // Backed out of unlocking the vault: stay in the form.
        }
        catch (Exception e)
        {
            Prompts.Error("Couldn't save the credential", Errors.Describe(e));
        }
        finally
        {
            SetBusy(false);
        }
    }
}

/// <summary>
/// Assigns a credential to a folder. Connections inside it (and its
/// subfolders) whose authentication is "Use the folder's credential" use it,
/// with the nearest folder winning.
/// </summary>
internal sealed class FolderCredentialDialog : EditorWindow
{
    private string? selection;

    public FolderCredentialDialog(AppModel model, string folder) : base("Folder Credential", 520, 480)
    {
        AutomationProperties.SetAutomationId(this, "FolderCredentialDialog");
        model.FolderCredentials.TryGetValue(folder, out selection);

        var form = new FormBuilder();
        form.Section("Folder credential");
        form.Row("Folder", new TextBlock { Text = folder, TextWrapping = TextWrapping.Wrap, VerticalAlignment = VerticalAlignment.Center });
        var inherited = model.InheritedCredential(FolderPath.Parent(folder));
        TextBlock? fallback = null;
        var picker = CredentialPicker.Create(model.Credentials, "None", selection, id =>
        {
            selection = id;
            if (fallback is not null) fallback.Visibility = id is null ? Visibility.Visible : Visibility.Collapsed;
        }, "Credential");
        form.Row("Credential", picker);
        form.Note("Connections in this folder and its subfolders set to “Use the folder's credential” use it. " +
                  "A credential on a nearer folder wins.");
        if (inherited is { } found)
        {
            fallback = form.Note($"With none set here they use “{found.Credential.Name}” from “{found.Folder}”.");
            fallback.Visibility = selection is null ? Visibility.Visible : Visibility.Collapsed;
        }
        SetForm(form);

        AddButton("Save", () =>
        {
            try
            {
                model.SetFolderCredential(folder, selection);
                Accept();
            }
            catch (Exception e)
            {
                Prompts.Error("Couldn't set the folder credential", Errors.Describe(e));
            }
        }, isDefault: true, automationId: "EditorSave");
        AddButton("Cancel", Close, isCancel: true, automationId: "EditorCancel");
    }
}
