using System.IO;
using System.Windows;
using System.Windows.Automation;
using System.Windows.Controls;
using System.Windows.Controls.Primitives;
using Toolbox.Model;

namespace Toolbox.Sidebar;

/// <summary>The New/Edit Connection dialog.</summary>
internal sealed class ConnectionEditor : EditorWindow
{
    private readonly AppModel model;
    private readonly ConnectionDraft draft;
    private readonly TextBlock folderNote;
    private readonly Dictionary<ConnectionFamily, RadioButton> familyButtons = new();
    private readonly ComboBox protocol = new();
    private readonly ComboBox method = new() { HorizontalAlignment = HorizontalAlignment.Stretch };

    private static readonly (ConnectionKind Kind, string Label)[] Protocols =
    [
        (ConnectionKind.Sftp, "SFTP (over SSH)"),
        (ConnectionKind.Ftps, "FTP over TLS (explicit FTPS)"),
        (ConnectionKind.Ftp, "FTP (not encrypted)"),
    ];

    public ConnectionEditor(AppModel model, ConnectionDraft draft)
        : base(draft.IsNew ? "New Connection" : "Edit Connection", 600, 780)
    {
        this.model = model;
        this.draft = draft;
        DataContext = draft;
        AutomationProperties.SetAutomationId(this, "ConnectionEditor");

        var form = new FormBuilder();
        form.Section("Connection");
        form.Row("Type", FamilyPicker());
        form.Row("Protocol", ProtocolPicker(), nameof(ConnectionDraft.IsFileTransfer));
        form.Row("Name", FormBuilder.Text(nameof(ConnectionDraft.Name), "nutanix1"));
        form.Row("Host", FormBuilder.Text(nameof(ConnectionDraft.Host), "hostname or IP"));
        form.Row("Port", FormBuilder.Text(nameof(ConnectionDraft.Port)));
        form.Row("Folder", FormBuilder.Text(nameof(ConnectionDraft.Folder), "Optional; use / for subfolders"));
        form.Note("The desktop follows the pane size.", nameof(ConnectionDraft.IsRdp));
        form.Note("Plain FTP sends the password and files unencrypted. Prefer SFTP or FTPS when the server offers them.",
                  nameof(ConnectionDraft.IsPlainFtp), warning: true);

        form.Section("Authentication");
        // Wired by hand (see Refresh): the list of methods changes with the
        // connection type, and a bound drop-down drops its selection when its
        // list is replaced.
        AutomationProperties.SetAutomationId(method, "AuthMethod");
        method.SelectionChanged += (_, _) =>
        {
            if (method.SelectedItem is Choice<AuthMethod> choice) draft.AuthMethod = choice.Value;
        };
        form.Row("Method", method);
        form.Row("Username", FormBuilder.Text(nameof(ConnectionDraft.Username), hintPath: nameof(ConnectionDraft.UsernameHint)),
                 nameof(ConnectionDraft.NeedsUsername));

        var picker = CredentialPicker.Create(model.Credentials, "Choose…", draft.CredentialId,
                                             id => draft.CredentialId = id, "Credential");
        form.Row("Credential", picker, nameof(ConnectionDraft.UsesCredential));
        form.Note("The credential supplies the username and the secret.", nameof(ConnectionDraft.UsesCredential));
        if (model.Credentials.Count == 0)
        {
            form.Note("No credentials yet. Add one with File > New Credential.", nameof(ConnectionDraft.UsesCredential));
        }

        form.Row("Password", FormBuilder.Secret(value => draft.Password = value, "Password"), nameof(ConnectionDraft.UsesStored));
        form.Note(null, nameof(ConnectionDraft.UsesStored), textPath: nameof(ConnectionDraft.StoredPasswordNote));

        folderNote = form.Note("", nameof(ConnectionDraft.UsesFolder));

        form.Note("You'll be asked for the password every time.", nameof(ConnectionDraft.UsesPrompt));

        form.Row("Private key", KeyFileRow(), nameof(ConnectionDraft.UsesKeyFile));
        form.Note("An encrypted key prompts for its passphrase on connect.", nameof(ConnectionDraft.UsesKeyFile));

        form.Row("Agent pipe", FormBuilder.Text(nameof(ConnectionDraft.AgentSocket), @"Blank uses \\.\pipe\openssh-ssh-agent"),
                 nameof(ConnectionDraft.UsesAgent));
        form.Note("The Windows OpenSSH agent and 1Password's SSH agent both answer on the default pipe.",
                  nameof(ConnectionDraft.UsesAgent));

        form.Note("Generated by a provider. The next sync replaces your edits.", nameof(ConnectionDraft.IsGenerated), warning: true);
        SetForm(form);

        AddButton(draft.IsNew ? "Add" : "Save", Save, isDefault: true, automationId: "EditorSave");
        AddButton("Cancel", Close, isCancel: true, automationId: "EditorCancel");

        draft.PropertyChanged += (_, _) => Refresh();
        Refresh();
    }

    /// <summary>The saved connection, once the dialog has closed with Save.</summary>
    public Connection? Saved { get; private set; }

    private FrameworkElement FamilyPicker()
    {
        var panel = new UniformGrid { Rows = 1 };
        var toggle = TryFindResource(typeof(ToggleButton)) as Style;
        foreach (var family in new[] { ConnectionFamily.Ssh, ConnectionFamily.Rdp, ConnectionFamily.Vnc, ConnectionFamily.Files })
        {
            var button = new RadioButton
            {
                Content = family.Label(),
                GroupName = "ConnectionFamily",
                Margin = new Thickness(0, 0, 4, 0),
                Padding = new Thickness(4, 5, 4, 5),
                HorizontalAlignment = HorizontalAlignment.Stretch,
                HorizontalContentAlignment = HorizontalAlignment.Center,
            };
            if (toggle is not null) button.Style = toggle;
            AutomationProperties.SetAutomationId(button, "Family" + family);
            button.Checked += (_, _) => draft.Family = family;
            familyButtons[family] = button;
            panel.Children.Add(button);
        }
        return panel;
    }

    private ComboBox ProtocolPicker()
    {
        protocol.ItemsSource = Protocols.Select(p => p.Label).ToList();
        protocol.HorizontalAlignment = HorizontalAlignment.Stretch;
        AutomationProperties.SetAutomationId(protocol, "Protocol");
        protocol.SelectionChanged += (_, _) =>
        {
            if (protocol.SelectedIndex >= 0 && draft.IsFileTransfer) draft.Kind = Protocols[protocol.SelectedIndex].Kind;
        };
        return protocol;
    }

    private FrameworkElement KeyFileRow()
    {
        var grid = new Grid();
        grid.ColumnDefinitions.Add(new ColumnDefinition { Width = new GridLength(1, GridUnitType.Star) });
        grid.ColumnDefinitions.Add(new ColumnDefinition { Width = GridLength.Auto });
        var box = FormBuilder.Text(nameof(ConnectionDraft.KeyPath), @"~\.ssh\id_ed25519");
        var choose = new Button { Content = "Choose…", Margin = new Thickness(6, 0, 0, 0) };
        choose.Click += (_, _) => ChooseKey();
        Grid.SetColumn(choose, 1);
        grid.Children.Add(box);
        grid.Children.Add(choose);
        return grid;
    }

    private void ChooseKey()
    {
        var dialog = new Microsoft.Win32.OpenFileDialog
        {
            Title = "Choose a private key",
            CheckFileExists = true,
            Filter = "All files (*.*)|*.*",
        };
        var ssh = Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.UserProfile), ".ssh");
        if (Directory.Exists(ssh)) dialog.InitialDirectory = ssh;
        if (dialog.ShowDialog(this) == true) draft.KeyPath = dialog.FileName;
    }

    /// <summary>Brings the hand-wired controls in line with the draft.</summary>
    private void Refresh()
    {
        if (familyButtons.TryGetValue(draft.Family, out var button) && button.IsChecked != true) button.IsChecked = true;
        var index = Array.FindIndex(Protocols, p => p.Kind == draft.Kind);
        if (index >= 0 && protocol.SelectedIndex != index) protocol.SelectedIndex = index;

        if (!ReferenceEquals(method.ItemsSource, draft.AuthMethodChoices)) method.ItemsSource = draft.AuthMethodChoices;
        if (!Equals(method.SelectedItem, draft.SelectedAuthMethod)) method.SelectedItem = draft.SelectedAuthMethod;

        var inherited = model.InheritedCredential(draft.Folder.BlankToNull());
        if (inherited is { } found)
        {
            folderNote.Text = $"Uses “{found.Credential.Name}” from folder “{found.Folder}”. " +
                              "A credential on a nearer folder takes over automatically.";
            folderNote.SetResourceReference(TextBlock.ForegroundProperty, "TextFillColorSecondaryBrush");
        }
        else
        {
            folderNote.Text = "No folder above this connection has a credential yet. Right-click a folder in the " +
                              "sidebar and choose Set Credential…, then pick this method.";
            folderNote.SetResourceReference(TextBlock.ForegroundProperty, "SystemFillColorCautionBrush");
        }
    }

    private async void Save()
    {
        if (draft.ValidationError is { } problem)
        {
            ShowValidation(problem);
            return;
        }
        ShowValidation(null);
        SetBusy(true);
        try
        {
            Saved = await model.SaveAsync(draft.ToConnection(), draft.StoredPassword());
            Accept();
        }
        catch (VaultException e) when (e.IsCancellation)
        {
            // Backed out of unlocking the vault: stay in the form.
        }
        catch (Exception e)
        {
            Prompts.Error("Couldn't save the connection", Errors.Describe(e));
        }
        finally
        {
            SetBusy(false);
        }
    }
}
