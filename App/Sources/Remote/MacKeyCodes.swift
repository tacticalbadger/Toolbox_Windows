import AppKit

/// macOS virtual key codes (ANSI layout) to PC/AT set 1 scancodes as RDP
/// expects them. `extended` marks keys sent with the E0 prefix.
enum MacKeyCodes {
    struct Scancode {
        let code: UInt8
        let extended: Bool
    }

    static func scancode(forKeyCode keyCode: UInt16) -> Scancode? {
        table[keyCode]
    }

    /// Which modifier key a flags-changed event refers to, by key code.
    static func isModifier(_ keyCode: UInt16) -> Bool {
        [0x36, 0x37, 0x38, 0x39, 0x3A, 0x3B, 0x3C, 0x3D, 0x3E].contains(keyCode)
    }

    private static let table: [UInt16: Scancode] = {
        var t: [UInt16: Scancode] = [:]
        func k(_ mac: UInt16, _ pc: UInt8, ext: Bool = false) { t[mac] = Scancode(code: pc, extended: ext) }
        // Letters
        k(0x00, 0x1E); k(0x01, 0x1F); k(0x02, 0x20); k(0x03, 0x21); k(0x04, 0x23); k(0x05, 0x22)
        k(0x06, 0x2C); k(0x07, 0x2D); k(0x08, 0x2E); k(0x09, 0x2F); k(0x0B, 0x30); k(0x0C, 0x10)
        k(0x0D, 0x11); k(0x0E, 0x12); k(0x0F, 0x13); k(0x10, 0x15); k(0x11, 0x14); k(0x1F, 0x18)
        k(0x20, 0x16); k(0x22, 0x17); k(0x23, 0x19); k(0x25, 0x26); k(0x26, 0x24); k(0x28, 0x25)
        k(0x2D, 0x31); k(0x2E, 0x32)
        // Digits and punctuation
        k(0x12, 0x02); k(0x13, 0x03); k(0x14, 0x04); k(0x15, 0x05); k(0x17, 0x06); k(0x16, 0x07)
        k(0x1A, 0x08); k(0x1C, 0x09); k(0x19, 0x0A); k(0x1D, 0x0B); k(0x1B, 0x0C); k(0x18, 0x0D)
        k(0x21, 0x1A); k(0x1E, 0x1B); k(0x29, 0x27); k(0x27, 0x28); k(0x32, 0x29); k(0x2A, 0x2B)
        k(0x2B, 0x33); k(0x2F, 0x34); k(0x2C, 0x35); k(0x0A, 0x56)
        // Control keys
        k(0x24, 0x1C); k(0x30, 0x0F); k(0x31, 0x39); k(0x33, 0x0E); k(0x35, 0x01)
        k(0x39, 0x3A)
        k(0x38, 0x2A); k(0x3C, 0x36)              // shift
        k(0x3B, 0x1D); k(0x3E, 0x1D, ext: true)   // control
        k(0x3A, 0x38); k(0x3D, 0x38, ext: true)   // option → alt
        k(0x37, 0x5B, ext: true); k(0x36, 0x5C, ext: true) // command → windows
        // Navigation
        k(0x72, 0x52, ext: true); k(0x73, 0x47, ext: true); k(0x74, 0x49, ext: true)
        k(0x75, 0x53, ext: true); k(0x77, 0x4F, ext: true); k(0x79, 0x51, ext: true)
        k(0x7B, 0x4B, ext: true); k(0x7C, 0x4D, ext: true); k(0x7D, 0x50, ext: true); k(0x7E, 0x48, ext: true)
        // Function keys
        k(0x7A, 0x3B); k(0x78, 0x3C); k(0x63, 0x3D); k(0x76, 0x3E); k(0x60, 0x3F); k(0x61, 0x40)
        k(0x62, 0x41); k(0x64, 0x42); k(0x65, 0x43); k(0x6D, 0x44); k(0x67, 0x57); k(0x6F, 0x58)
        k(0x69, 0x37, ext: true)  // F13 → print screen
        k(0x6B, 0x46)             // F14 → scroll lock
        k(0x6A, 0x67); k(0x40, 0x68); k(0x4F, 0x69); k(0x50, 0x6A); k(0x5A, 0x6B)
        // Keypad
        k(0x52, 0x52); k(0x53, 0x4F); k(0x54, 0x50); k(0x55, 0x51); k(0x56, 0x4B); k(0x57, 0x4C)
        k(0x58, 0x4D); k(0x59, 0x47); k(0x5B, 0x48); k(0x5C, 0x49); k(0x41, 0x53); k(0x43, 0x37)
        k(0x45, 0x4E); k(0x4E, 0x4A); k(0x4B, 0x35, ext: true); k(0x4C, 0x1C, ext: true)
        k(0x47, 0x45); k(0x51, 0x0D)
        return t
    }()
}
